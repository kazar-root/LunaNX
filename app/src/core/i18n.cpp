const std::vector<UiLanguageOption>& UiLanguageOptions()
{
    // Ordre alphabétique des noms français : allemand, anglais, chinois simplifié, espagnol,
    // français, italien, portugais, russe. Chaque langue est affichée dans sa propre langue.
    static const std::vector<UiLanguageOption> options = {
        {"de", "Deutsch"},
        {"en", "English"},
        {"zh", "简体中文"},
        {"es", "Español"},
        {"fr", "Français"},
        {"it", "Italiano"},
        {"pt", "Português"},
        {"ru", "Русский"},
    };
    return options;
}

bool IsSupportedUiLanguage(const std::string& code)
{
    for (const auto& option : UiLanguageOptions())
        if (code == option.code)
            return true;
    return false;
}

void SetUiLanguage(const std::string& code)
{
    g_language = IsSupportedUiLanguage(code) ? code : "en";
}

const std::string& UiLanguage()
{
    return g_language;
}

std::string Tr(const std::string& french)
{
    const int column = LanguageColumn(g_language);
    if (column < 0)
        return french;
    const auto& index = TranslationIndex();
    const auto found = index.find(french);
    if (found == index.end())
        return french;
    const char* text = found->second->texts[column];
    return text && *text ? text : found->second->texts[0];
}

std::string TrFormat(const std::string& french, std::initializer_list<std::string> args)
{
    std::string text = Tr(french);
    size_t position = 0;
    for (const auto& arg : args)
    {
        position = text.find("{}", position);
        if (position == std::string::npos)
            break;
        text.replace(position, 2, arg);
        position += arg.size();
    }
    return text;
}

