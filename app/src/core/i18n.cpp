int LanguageColumn(const std::string& code)
{
    static const char* const kColumns[] = {"en", "de", "es", "it", "pt", "ru", "zh", "pl", "nl", "sv"};
    for (int i = 0; i < 10; ++i)
        if (code == kColumns[i])
            return i;
    return -1;
}

