int LanguageColumn(const std::string& code)
{
    static const char* const kColumns[] = {"en", "de", "es", "it", "pt", "ru", "zh"};
    for (int i = 0; i < 7; ++i)
        if (code == kColumns[i])
            return i;
    return -1;
}

const std::unordered_map<std::string, const Translation*>& TranslationIndex()
{
    static const std::unordered_map<std::string, const Translation*> index = [] {
        std::unordered_map<std::string, const Translation*> map;
        for (const auto& translation : kTranslations)
            map.emplace(translation.french, &translation);
        return map;
    }();
    return index;
}

